import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const java = readFileSync(new URL('../android/app/src/main/java/com/aizeek/newsnook/BrowserHostPlugin.java', import.meta.url), 'utf8')
const begin = java.indexOf('private void showTabContent(Tab tab, Tab previous)')
const end = java.indexOf('private void layoutBackgroundAgent()', begin)
const switchCode = java.slice(begin, end)
assert.ok(begin >= 0 && end > begin)
assert.doesNotMatch(switchCode, /Bitmap\.createBitmap|\.draw\(canvas\)|\.compress\(/, 'native tab transitions must not allocate and draw a full-screen screenshot')
assert.match(switchCode, /frame\.addView\(outgoing/, 'retain the actual outgoing WebView during the crossfade')
assert.match(switchCode, /frame\.addView\(incoming/, 'show the actual incoming WebView')
assert.match(switchCode, /child\.animate\(\)\.cancel\(\)/, 'interruptible tab switches cancel unfinished native transitions')
assert.match(switchCode, /current == tab/, 'stale transition completion cannot remove a newer active tab')
assert.match(java, /Executors\.newSingleThreadExecutor/, 'preview encoding is serialized off the Android UI thread')
assert.match(java, /notifyListeners\("tabPreviewReady"/, 'thumbnail result arrives without blocking the tab switcher')
const flyerBegin = java.indexOf('private void animatePaperFlyIntoTabBadge(')
const flyerEnd = java.indexOf('private void finishPreparedNavigation(', flyerBegin)
const flyer = java.slice(flyerBegin, flyerEnd)
assert.ok(flyerBegin >= 0 && flyerEnd > flyerBegin)
assert.doesNotMatch(flyer, /view\.draw\(canvas\)/, 'background-tab flight does not synchronously rasterize a full webpage')
assert.match(flyer, /PixelCopy\.request\(/, 'paper flight preserves a webpage thumbnail using nonblocking native copy')
assert.ok(flyer.indexOf('createTab(targetUrl, null, false, source.id);') < flyer.indexOf('PixelCopy.request('), 'background tab is created before screenshot completion')
assert.match(flyer, /if \(started\[0\]\) return/, 'late screenshot callbacks cannot double-start the animation')
console.log('browser-native-transition-performance: live WebView crossfade, no UI screenshot and async thumbnails OK')
